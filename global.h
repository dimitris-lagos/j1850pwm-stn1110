/* ============================================================================
 *  ΜΟΝΤΕΛΟ ΚΑΤΑΝΑΛΩΣΗΣ ΚΑΥΣΙΜΟΥ
 * ============================================================================
 * Η ECU σε closed loop κρατάει το μείγμα στοιχειομετρικό (λ = 1). Άρα:
 *
 *      καύσιμο [g/s] = αέρας [g/s] / AFR_STOICH
 *      καύσιμο [L/s] = καύσιμο [g/s] / FUEL_DENSITY_G_L
 *
 * Ο αέρας έρχεται από το PID 0x10 (MAF) σε βήματα των 0.01 g/s.
 *
 * Το AFR είναι αυτό του καυσίμου που βάζεις: ο αισθητήρας λ δεν ξέρει τι καίγεται,
 * απλά κρατάει λ = 1. Καθαρή βενζίνη 14.7, E5 ~14.4, E10 ~14.1.
 * Η πυκνότητα κατά EN 228 είναι 720-775 g/L, τυπικά ~745. */
#define AFR_STOICH        14.4f    // E5. Βάλε 14.7 για καθαρή βενζίνη, 14.1 για E10
#define FUEL_DENSITY_G_L  745.0f   // g/L (EN 228: 720-775)

/* Σταθερά που μετατρέπει ΑΠΕΥΘΕΙΑΣ το raw του PID 0x10 σε µL/s καυσίμου:
 *      µL/s = raw × 0.01 g/s ÷ (AFR × ρ) g/L × 1e6 µL/L = raw × 10000 / (AFR × ρ)
 * Υπολογίζεται στη μεταγλώττιση. Ένας float πολλαπλασιασμός ανά δείγμα,
 * καμία διαίρεση στον χρόνο εκτέλεσης (η float διαίρεση στον AVR κοστίζει
 * ~5× τον πολλαπλασιασμό). */
#define UL_PER_SEC_PER_MAF_COUNT (10000.0f / (AFR_STOICH * FUEL_DENSITY_G_L))

/* ----------------------------------------------------------------------------
 *  Διορθώσεις εκτός closed loop (PID 0x03 = Fuel System Status)
 * ----------------------------------------------------------------------------
 * Η παραδοχή λ = 1 ισχύει ΜΟΝΟ σε closed loop. Σε open loop η ECU εμπλουτίζει:
 *  - Φορτίο / tip-in: λ ≈ 0.85-0.90, δηλαδή 10-18% περισσότερο καύσιμο για την
 *    ίδια μάζα αέρα. Στην πόλη με συχνά ξεκινήματα είναι μεγάλο ποσοστό του
 *    χρόνου, οπότε εκεί η διόρθωση έχει και τη μεγαλύτερη σημασία.
 *  - Κρύος κινητήρας: εμπλουτισμός μέχρι να ζεσταθεί ο αισθητήρας λ.
 * Οι συντελεστές είναι αρχικές εκτιμήσεις. Ρυθμίζονται με γέμισμα ως το κλικ
 * σε δύο διαδρομές (πόλη / εθνική), βλ. το σχόλιο της sample_fuel().
 *
 * ΠΡΟΣΟΧΗ: Το bit 0x04 σημαίνει "open loop λόγω φορτίου Ή λόγω κοπής καυσίμου
 * στο ρολάρισμα". Αν το EEC-V κάνει fuel cut (MAF χαμηλός, τάση O2 κολλημένη
 * κάτω από 0.2 V, ταχύτητα > 0), τότε εκεί το καύσιμο είναι 0 και όχι ×1.12.
 * Δεν το έχουμε επιβεβαιώσει στο Focus Mk1. Ελέγχεται από τη σελίδα 4. */
#define OPEN_LOOP_LOAD_FACTOR  1.12f
#define OPEN_LOOP_COLD_FACTOR  1.10f

/* Bits του byte A του PID 0x03 */
#define FSTAT_OPEN_LOOP_COLD     0x01   // Open loop, δεν έχει ζεσταθεί
#define FSTAT_CLOSED_LOOP        0x02   // Closed loop, χρήση αισθητήρα O2
#define FSTAT_OPEN_LOOP_LOAD     0x04   // Open loop λόγω φορτίου ή decel fuel cut
#define FSTAT_OPEN_LOOP_FAULT    0x08   // Open loop λόγω βλάβης
#define FSTAT_CLOSED_LOOP_FAULT  0x10   // Closed loop με βλάβη σε έναν O2

/* ----------------------------------------------------------------------------
 *  Fuel trims
 * ----------------------------------------------------------------------------
 * Τα trims είναι η διόρθωση που κάνει η ECU στον βασικό χάρτη ψεκασμού για να
 * πετύχει λ = 1. Όταν ο MAF υπομετρά τον αέρα (βρώμικο hot-wire, συχνό στο
 * Focus Mk1) η ECU το αντισταθμίζει με θετικά trims, οπότε:
 *      πραγματικό καύσιμο = MAF_reported × (1 + (STFT+LTFT)/100) / AFR
 * Το LTFT κρατά τη μόνιμη διόρθωση και εφαρμόζεται από την ECU πάντα. Το STFT
 * ταλαντώνεται γύρω από το LTFT και σε open loop παγώνει στο 0, οπότε
 * προστίθεται μόνο σε closed loop. Τα δύο μαζί δίνουν τη συνολική διόρθωση.
 *
 * 1 = εφαρμογή STFT+LTFT σε closed loop, LTFT σε open loop.   0 = μόνο MAF/AFR.
 * Έλεγχος ορθότητας: στη σελίδα 4 το LTFT στο ρελαντί έναντι στην εθνική, και
 * σύγκριση του συνόλου (σελίδα 2) με την αντλία στο γέμισμα. */
#define APPLY_FUEL_TRIMS  1

/* Χωρητικότητα ρεζερβουάρ για τη μετατροπή % → λίτρα */
#define FUEL_TANK_LITERS  55.0f

/* Ρυθμός ανανέωσης της οθόνης. Το lcd.clear() κοστίζει ~2 ms νεκρή αναμονή
 * και οι 32 χαρακτήρες άλλα ~3 ms. Με το loop() στα ~200 ms δεν έχει νόημα να
 * ξαναγράφουμε (και να τρεμοπαίζει) την οθόνη σε κάθε κύκλο. */
#define LCD_REFRESH_MS  400

